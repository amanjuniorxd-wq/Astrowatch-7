"""
Astrowatch -- national ("mundane") kundli corpus: real formation/independence
dates for UN member states, per the user's explicit rule (see
MUNDANE_ASTROLOGY_RULE.md): a nation's kundli is computed from its real formation
date + capital-city location, with time assumed 00:00 local civil time whenever
(as is true for virtually every nation -- unlike a hospital birth certificate,
no government records "the minute" of founding) no specific documented time
exists. Every entry here uses the ASSUMED_MIDNIGHT default via
astrowatch/mundane/entity_chart.py; none claim a documented time.

DATA HONESTY (same convention as famous_people_corpus.py / leaders_corpus.py):
- Dates are drawn from general, well-established historical/civic knowledge --
  the kind taught in standard reference works (encyclopedias, national
  statistical/foreign-ministry sites, UN membership records), not individually
  live-verified for all ~193 entries. A sample across regions/eras (recent
  secessions: South Sudan, Kosovo, Timor-Leste, Montenegro; post-Soviet/
  post-Yugoslav breakups; and a few contested/ambiguous cases) WAS spot-checked
  via live web search this session -- see git commit message for which ones.
- CHOICE OF REFERENCE DATE for long-continuously-existing states (UK, France,
  Japan, China, Russia, etc.) is a real methodological choice, not a claim that
  the nation was "born" on that date -- these states have no single objective
  founding instant. This corpus uses the most common convention in existing
  mundane-astrology practice AND/OR the most recent full-sovereignty/current-
  constitution milestone (documented per-country in the `note` field): e.g. USA
  uses the 1776 Declaration of Independence; modern Germany uses 1990
  reunification, not the much older Holy Roman Empire or 1871 unification;
  Russia uses the 1991 dissolution of the USSR, not the founding of Kievan Rus'.
  A different, equally defensible convention would produce different charts --
  this is disclosed, not hidden.
- CAPITAL COORDINATES: city-level, 2 decimal places, same precision convention
  as the rest of this project's location data.
- TIMEZONE: the IANA zone valid for that capital today; for dates before a
  zone's modern rules existed, Python's zoneinfo still resolves the best
  available historical offset it has data for (same caveat as timeutil.py
  documents for very old dates generally).
"""

